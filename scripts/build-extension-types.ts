import { lstat, mkdir, readFile, readdir, realpath, rm, writeFile } from "node:fs/promises";
import { basename, dirname, isAbsolute, join, relative, resolve, sep } from "node:path";

const root = await realpath(resolve(import.meta.dir, ".."));
const marker = ".schway-extension-types";
const signature = "Generated by Schway build-extension-types v1\n";

/** Resolve existing ancestors, refusing dangling aliases instead of treating them as new paths. */
async function canonicalPath(path: string): Promise<string> {
  try {
    return await realpath(path);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    if (await entry(path)) throw new Error("Cannot resolve the output symlink.");
    return join(await canonicalPath(dirname(path)), basename(path));
  }
}

/** Inspect an entry without following symlinks, returning undefined only when it is absent. */
async function entry(path: string) {
  try { return await lstat(path); }
  catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
    return undefined;
  }
}

/** Identify a directory and its descendants using path boundaries rather than string prefixes. */
function within(path: string, directory: string): boolean {
  const suffix = relative(directory, path);
  return suffix === "" || (suffix !== ".." && !suffix.startsWith(`..${sep}`) && !isAbsolute(suffix));
}

/** Refuse cleanup unless the entire tree contains only regular emitted declarations and its root marker. */
async function validateGeneratedTree(path: string, top = true): Promise<void> {
  if (top && (!(await entry(join(path, marker)))?.isFile() || await readFile(join(path, marker), "utf8") !== signature)) {
    throw new Error("Output is not a generated declaration directory.");
  }
  for (const item of await readdir(path, { withFileTypes: true })) {
    if (item.isDirectory()) await validateGeneratedTree(join(path, item.name), false);
    else if (!item.isFile() || !(item.name.endsWith(".d.ts") || (top && item.name === marker))) {
      throw new Error("Output contains files other than generated declarations.");
    }
  }
}

/** Validate the canonical cleanup boundary before removing any existing output. */
async function outputDirectory(path: string): Promise<string> {
  const out = await canonicalPath(path);
  const protectedPaths = await Promise.all(["src", "node_modules"].map(name => canonicalPath(join(root, name))));
  if (within(root, out) || protectedPaths.some(path => within(out, path) || within(path, out)) ||
      (within(out, root) && !within(out, join(root, "dist")))) {
    throw new Error("Output overlaps repository sources or dependencies.");
  }
  const existing = await entry(out);
  if (existing) {
    if (!existing.isDirectory()) throw new Error("Output is not a directory.");
    await validateGeneratedTree(out);
  }
  return out;
}

const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== "--out" || !args[1])) {
  console.error("Use bun scripts/build-extension-types.ts [--out <dir>].");
  process.exit(1);
}
let out: string;
try {
  out = await outputDirectory(resolve(root, args[1] ?? "dist/types"));
} catch (error) {
  console.error(`Cannot clean declaration output: ${error instanceof Error ? error.message : String(error)} Choose a new output directory.`);
  process.exit(1);
}
await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await writeFile(join(out, marker), signature);
const proc = Bun.spawn([
  resolve(root, "node_modules/.bin/tsc"), "--ignoreConfig", "src/extensions/index.ts", "src/host/index.ts",
  "--declaration", "--emitDeclarationOnly", "--outDir", out, "--rootDir", "src",
  "--lib", "ESNext", "--target", "ESNext", "--module", "ESNext",
  "--moduleResolution", "bundler", "--strict", "--skipLibCheck",
  "--allowImportingTsExtensions", "--verbatimModuleSyntax", "--types", "bun",
], { cwd: root, stdout: "inherit", stderr: "inherit" });
process.exit(await proc.exited);
